std::atomic<int64_t> utils::AutoGeneratedId::_idCounter;


utils::AutoGeneratedId::AutoGeneratedId() : _uuid(generateGUID()) {
    this->_id = this->_idCounter.fetch_add(1, std::memory_order::memory_order_relaxed);
}

utils::AutoGeneratedId::~AutoGeneratedId() {
}

const std::string &utils::AutoGeneratedId::getString() const {
    return this->_uuid;
}

int64_t utils::AutoGeneratedId::getInt() const {
    return this->_id;
}


static size_t _estimateDecodedLength(const std::string &input) {
	size_t len     = input.length();
	size_t padding = 0;

	if (input[len - 1] == '=' && input[len - 2] == '=') {//last two chars are =
		padding = 2;

	} else if (input[len - 1] == '=') {//last char is =
		padding = 1;
	}

	return (len * 3) / 4 - padding;
}

