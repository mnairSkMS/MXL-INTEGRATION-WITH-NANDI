TEST(lib_license_crypto, sha256_simple) {

    // dd if=/dev/urandom bs=1024 count=1 > data.bin
    // cat data.bin | xxd -i
    // cat data.bin | openssl  dgst -sha256 -binary | xxd -i
    auto hasher = crypto::getCryptoManager().newHasher(crypto::HashAlgorithm::SHA256);

    {
        hasher->update(data);

        ASSERT_TRUE(std::equal(expected.begin(), expected.end(), hasher->final().begin()));
    }
}


TEST(lib_license_crypto, sha256_reuse) {

    // dd if=/dev/urandom bs=1024 count=1 > data.bin
    // cat data.bin | xxd -i
    // cat data.bin | openssl  dgst -sha256 -binary | xxd -i
    auto hasher = crypto::getCryptoManager().newHasher(crypto::HashAlgorithm::SHA256);

    {
        hasher->update(data);

        ASSERT_TRUE(std::equal(expected.begin(), expected.end(), hasher->final().begin()));

        hasher->reset();

        hasher->update(data);

        ASSERT_TRUE(std::equal(expected.begin(), expected.end(), hasher->final().begin()));
    }
}