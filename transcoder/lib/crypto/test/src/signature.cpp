#include <gtest/gtest.h>

#include "utpl/crypto/manager.h"

using namespace utpl;

// dd if=/dev/urandom  bs=123 count=1 | tee data.txt | xxd -i
// openssl pkeyutl -verify -pubin -inkey transcoder/license/keys/devel/license_ed25519_public_key.der -rawin -in data.bin -sigfile signature.bin
// openssl pkeyutl -sign -inkey transcoder/license/keys/devel/license_ed25519_private_key.der -out signature.bin -rawin -in data.bin
//
// openssl asn1parse -in transcoder/license/keys/devel/license_ed25519_private_key.der -inform der
TEST(lib_license_crypto, ed25519) {
    const std::vector<uint8_t> publicKey = {
        0x30, 0x2a, 0x30, 0x05, 0x06, 0x03, 0x2b, 0x65, 0x70, 0x03, 0x21, 0x00,
        0xa7, 0xfe, 0xf6, 0x30, 0x87, 0xa6, 0xd7, 0x25, 0xe8, 0xf8, 0x63, 0xb1,
        0x92, 0x1e, 0x0d, 0xd0, 0x70, 0xbd, 0x3f, 0x34, 0x8e, 0x29, 0x30, 0x03,
        0x40, 0xf2, 0x71, 0xaa, 0xbc, 0x37, 0x92, 0x41
    };

    const std::vector<uint8_t> privateKey = {
        0x30, 0x2e, 0x02, 0x01, 0x00, 0x30, 0x05, 0x06, 0x03, 0x2b, 0x65, 0x70,
        0x04, 0x22, 0x04, 0x20, 0x63, 0xc6, 0xdf, 0x42, 0xb5, 0x0d, 0x1e, 0xd4,
        0xde, 0x55, 0xe2, 0xdf, 0xb7, 0x89, 0x29, 0x6d, 0xde, 0xfe, 0xe4, 0xb4,
        0x65, 0x27, 0x8e, 0x1d, 0x6e, 0x98, 0x8d, 0xb0, 0xc0, 0x08, 0xbb, 0x91
    };

    const uint8_t data[] = {
        0x25, 0x39, 0x4e, 0x51, 0x96, 0xb3, 0xf1, 0x05, 0x08, 0xcf, 0x54, 0xb1,
        0xd8, 0x3d, 0xf9, 0xe3, 0xe2, 0x04, 0x0f, 0x94, 0x35, 0xcb, 0x9d, 0x9d,
        0x38, 0xf2, 0xc1, 0xd6, 0xea, 0x85, 0x0d, 0x59, 0xf1, 0x89, 0x6d, 0x6d,
        0x4c, 0x82, 0x38, 0x98, 0xa2, 0x35, 0x42, 0xa2, 0x97, 0x38, 0x71, 0x85,
        0x34, 0xa4, 0xd1, 0x17, 0xfc, 0xd2, 0x72, 0xab, 0x1b, 0xed, 0xf9, 0x56,
        0x10, 0x12, 0x3f, 0x96, 0x3b, 0x92, 0xd4, 0xda, 0x0a, 0x8f, 0xfa, 0xba,
        0xdd, 0x4c, 0x2a, 0xae, 0x75, 0x43, 0x36, 0x47, 0x0a, 0x9a, 0xa1, 0xc7,
        0x8a, 0x86, 0x9b, 0x7d, 0xab, 0xd6, 0xc4, 0x50, 0xc7, 0x60, 0xee, 0x17,
        0x63, 0x69, 0xfb, 0x9c, 0x77, 0xd5, 0xeb, 0x50, 0x63, 0x90, 0x48, 0x7c,
        0x63, 0x84, 0x71, 0x7d, 0x35, 0xd2, 0x5f, 0xe8, 0x27, 0x61, 0xcf, 0xed,
        0xb0, 0xd8, 0x94
    };

    const uint8_t expectedSignature[] = {
        0x8c, 0x13, 0xfa, 0x25, 0xdd, 0xd6, 0xc0, 0x7e, 0x33, 0x11, 0xdf, 0xd0,
        0xf5, 0x6e, 0xad, 0x94, 0x3f, 0x79, 0x31, 0x00, 0xf7, 0xe9, 0x27, 0xe0,
        0x38, 0x59, 0x25, 0xf7, 0xa6, 0x0c, 0x19, 0x2e, 0x93, 0xa1, 0xfb, 0x9c,
        0x2c, 0x3a, 0x14, 0x8d, 0x76, 0x9d, 0x17, 0xf9, 0x4f, 0xd3, 0x34, 0x11,
        0x38, 0x69, 0xe9, 0x2a, 0x10, 0xf5, 0x01, 0xda, 0x81, 0x21, 0x10, 0xa6,
        0xc7, 0x5c, 0x30, 0x0d
    };

    {
        auto &crypto = crypto::getCryptoManager();

        auto signature = crypto.newSignature(crypto::SignatureAlgorithm::ED25519);
        ASSERT_TRUE(signature);

        {
            auto pKey = crypto.loadPrivateKey(privateKey);
            ASSERT_TRUE(pKey);

            signature->initSign(*pKey);
            signature->update(data, sizeof(data));
            
            auto sign = signature->sign();

            ASSERT_TRUE(std::equal(expectedSignature, expectedSignature + sizeof(expectedSignature), sign.begin()));
        }

        {
            auto pKey = crypto.loadPublicKey(publicKey);
            ASSERT_TRUE(pKey);

            signature->initVerify(*pKey);
            signature->update(data, sizeof(data));
            
            ASSERT_TRUE(signature->verify(expectedSignature, sizeof(expectedSignature)));
        }
    }
}
