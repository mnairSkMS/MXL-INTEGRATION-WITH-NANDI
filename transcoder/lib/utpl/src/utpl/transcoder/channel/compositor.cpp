void transcoder::Compositor::prepare(const transcoder::VideoParameters &inParameters, pipeline::BinPtr &bin) {
    TRACE(("CALL"));

    this->_bin = bin;

    this->_layerSize.getDimension() = { inParameters.getWidth(), inParameters.getHeight() };

    auto id = std::to_string(utils::AutoGeneratedId().getInt());

    this->_compositor = bin->add(pipeline::Element::make("compositor-" + id, "compositor"));

    {
        this->_outputScaler = bin->add(pipeline::Element::make("compositor-output-scaler-" + id, "videoconvertscale"));
        this->_outputFilter = bin->add(pipeline::Element::make("compositor-output-filter-" + id, "capsfilter"));

        this->_compositor->link(this->_outputScaler);
        this->_outputScaler->link(this->_outputFilter);

        {
            auto caps = pipeline::Caps::create();

            caps->setMediaFormat(MediaType::VIDEO, Container::ES, Codec::ES);

            caps->setFormat(PixelFormat::BGRA);

            caps->setWidth(inParameters.getWidth());
            caps->setHeight(inParameters.getHeight());

            if (inParameters.getFramerate()) {
                caps->setFrameRate(inParameters.getFramerate());
            }

            this->_outputFilter->setProperty<GstCaps *>("caps", (*caps)->get());
        }

        this->_srcPad = this->_outputFilter->getPad("src");
    }

    // Set background - solid black
    this->_compositor->setProperty<GstAggregatorStartTimeSelection>("start-time-selection", GST_AGGREGATOR_START_TIME_SELECTION_FIRST);
    this->_compositor->setProperty<gint>("background", 1);

    // Create video layer
    {
        auto compositorPad = this->_compositor->requestPad("sink_%u");

        this->_videoLayer = std::make_shared<Layer>(bin, compositorPad, this->_layerSize, true, false);
        this->_videoLayer->setZOrder(PROGRAM_ZORDER);
    }
}

pipeline::PadPtr transcoder::Compositor::getSrcPad() const {
    return this->_srcPad;
}

std::shared_ptr<transcoder::Compositor::Layer> transcoder::Compositor::getVideoLayer() {
    return this->_videoLayer;
}

void transcoder::Compositor::setWindowSize(const Rectangle &rect) {
    std::unique_lock lock(this->_videoLayer->getMutex());

    DBG(("Requested compositor window set to: {}, {}, {}, {}",
     rect.x(), rect.y(), rect.width(), rect.height()
    ));

    if (this->_layerSize == rect) {
        DBG(("Skipping compositor window set, as the size has not changed."));

    } else {
        double scaleXFactor = (double) rect.width() / this->_layerSize.width();
        double scaleYFactor = (double) rect.height() / this->_layerSize.height();

        DBG(("Switching compositor window size from {}, {}, {}, {} to {}, {}, {}, {}, X factor {}, Y factor {}, graphic layers {}",
            this->_layerSize.x(), this->_layerSize.y(), this->_layerSize.width(), this->_layerSize.height(),
            rect.x(), rect.y(), rect.width(), rect.height(), scaleXFactor, scaleYFactor,
            this->_graphicLayers.size()
        ));

        for (auto &layer : this->_graphicLayers) {
            Rectangle inputWindow  = layer->getInputWindow();
            Rectangle outputWindow = layer->getOuputWindow();

            outputWindow.width (outputWindow.width()  * scaleXFactor);
            outputWindow.height(outputWindow.height() * scaleYFactor);
            
            outputWindow.x(outputWindow.x() * scaleXFactor);            
            outputWindow.y(outputWindow.y() * scaleYFactor);

            // Layer size does not change
            layer->setWindows(inputWindow, outputWindow);
        }

        this->_videoLayer->setSize(rect);

        {
            auto *writableCaps = gst_caps_make_writable(
                this->_outputFilter->getProperty<GstCaps *>("caps")
            );

            gst_caps_set_simple(writableCaps, 
                "width",  G_TYPE_INT, rect.width(), 
                "height", G_TYPE_INT, rect.height(), 
                nullptr
            );

            this->_outputFilter->setProperty<GstCaps *>("caps", writableCaps);

            gst_caps_unref(writableCaps);
        }

        this->_layerSize = rect;
    }
}

const Rectangle &transcoder::Compositor::getWindowSize() const {
    return this->_layerSize;
}

std::shared_ptr<transcoder::Compositor::Layer> transcoder::Compositor::createLayer() {
    if (this->_compositor) {
        auto compositorPad = this->_compositor->requestPad("sink_%u");

        auto layer = std::make_shared<Layer>(
            this->_bin, compositorPad, this->_layerSize, false, this->_createProxyPadsForLayers
        );
        layer->setZOrder(this->_nextOverlayZOrder++);
        this->_graphicLayers.push_back(layer);

        return *this->_graphicLayers.rbegin();
    }

    return nullptr;
}

void transcoder::Compositor::destroyLayer(std::shared_ptr<Layer> layer) {
    if (this->_compositor) {
        if (layer) {
            this->_compositor->releasePad(layer->getCompositorPad());
            this->_graphicLayers.erase(
                std::remove(this->_graphicLayers.begin(), this->_graphicLayers.end(), layer),
                this->_graphicLayers.end()
            );
        }
    }
}

void transcoder::Compositor::blank(bool blank) {
    gdouble val = blank ? 0 : 1.0;

    for (auto &pad : this->_compositor->getPads(false)) {
        pad->setProperty<gdouble>("alpha", val);
    }
}
