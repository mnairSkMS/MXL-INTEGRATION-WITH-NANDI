static constexpr guint PROGRAM_ZORDER = 100;


static void _addSource(GstObject *element, const std::string &propertyName, GstInterpolationMode mode) {
    GstControlSource *controlSource = gst_interpolation_control_source_new();

    gst_object_add_control_binding(element, 
        gst_direct_control_binding_new_absolute(element, propertyName.c_str(), controlSource)
    );

    g_object_set(controlSource, "mode", mode, NULL);

    gst_object_unref(controlSource);
}

static void _scheduleTransition(GstObject *object, const std::string &propertyName, GstClockTime startTime, int duration, float srcValue, float dstValue) {
        auto *binding = gst_object_get_control_binding(object, propertyName.c_str());

        if (binding) {
            GstTimedValueControlSource *source;

            g_object_get(binding, "control_source", &source, NULL);
            if (source) {
                gst_timed_value_control_source_unset_all(source);
                gst_timed_value_control_source_set(source, startTime, srcValue);
                gst_timed_value_control_source_set(source, startTime + GST_MSECOND * (int64_t) duration, dstValue);

                gst_object_unref(source);
            }

            gst_object_unref(binding);
        }
}

transcoder::Compositor::Layer::Layer(
    pipeline::BinPtr     binPtr,
    pipeline::PadPtr     compositorPad, 
    const Rectangle     &layerSize,
    bool                 cropEnabled,
    bool                 createProxyPad
) {
    this->_compositorPad = compositorPad;
    this->_layerSize     = layerSize;

    if (cropEnabled) {
        this->_cropElement = binPtr->add(pipeline::Element::make("crop-" + utpl::utils::AutoGeneratedId().getString(), "videocrop"));
    }

    {
        auto id = std::to_string(utils::AutoGeneratedId().getInt());

        auto convert = binPtr->add(pipeline::Element::make("compositor-conv-"   + id, "videoconvert"));
        auto filter  = binPtr->add(pipeline::Element::make("compositor-filter-" + id, "capsfilter"));

        convert->link(filter);

        {
            auto caps = pipeline::Caps::create();

            caps->setMediaFormat(MediaType::VIDEO, Container::ES, Codec::ES);
            caps->setFormat(PixelFormat::BGRA);

            filter->setProperty<GstCaps *>("caps", (*caps)->get());
        }

        if (this->_cropElement) {
            filter->link(this->_cropElement);

            this->_cropElement->getPad("src")->link(this->_compositorPad);

        } else {
            filter->getPad("src")->link(this->_compositorPad);
        }

        this->_sinkPad = convert->getPad("sink");

        filter->syncWithParent();
        convert->syncWithParent();

        if (this->_cropElement) {
            this->_cropElement->syncWithParent();
        }
    }

    if (createProxyPad) {
        this->_sinkPad = binPtr->addPad(std::string(), this->_sinkPad);
    }

    this->setWindows(this->_layerSize, this->_layerSize);

    // Alpha
    _addSource(GST_OBJECT((*this->_compositorPad)->get()), "alpha", GST_INTERPOLATION_MODE_CUBIC);

    // Output windows
    _addSource(GST_OBJECT((*this->_compositorPad)->get()), "xpos",   GST_INTERPOLATION_MODE_CUBIC);
    _addSource(GST_OBJECT((*this->_compositorPad)->get()), "ypos",   GST_INTERPOLATION_MODE_CUBIC);
    _addSource(GST_OBJECT((*this->_compositorPad)->get()), "width",  GST_INTERPOLATION_MODE_CUBIC);
    _addSource(GST_OBJECT((*this->_compositorPad)->get()), "height", GST_INTERPOLATION_MODE_CUBIC);

    // Input window
    if (this->_cropElement) {
        _addSource(GST_OBJECT((*this->_cropElement)->get()), "left",   GST_INTERPOLATION_MODE_CUBIC);
        _addSource(GST_OBJECT((*this->_cropElement)->get()), "top",    GST_INTERPOLATION_MODE_CUBIC);
        _addSource(GST_OBJECT((*this->_cropElement)->get()), "right",  GST_INTERPOLATION_MODE_CUBIC);
        _addSource(GST_OBJECT((*this->_cropElement)->get()), "bottom", GST_INTERPOLATION_MODE_CUBIC);
    }

    this->setOpacity(1.0);
}

void transcoder::Compositor::Layer::setZOrder(int order) {
    this->_compositorPad->setProperty<guint>("zorder", static_cast<guint>(order));
}

int transcoder::Compositor::Layer::getZOrder() const {
    return static_cast<int>(this->_compositorPad->getProperty<guint>("zorder"));
}


void transcoder::Compositor::Layer::setOpacity(float opacity, int transitionMs) {
    if (transitionMs == 0) {
        this->_compositorPad->setProperty<gdouble>("alpha", opacity);

    } else {
        auto &pad        = this->_compositorPad;
        auto clockSource = pad->getParent();
        
        _scheduleTransition(
            GST_OBJECT((*pad)->get()), 
            "alpha", 
            gst_element_get_current_running_time(clockSource.get()), 
            transitionMs, 
            pad->getProperty<gdouble>("alpha"), 
            opacity
        );
    }
}


float transcoder::Compositor::Layer::getOpacity() const {
    return this->_compositorPad->getProperty<gdouble>("alpha");
}


const Rectangle &transcoder::Compositor::Layer::getOuputWindow() const {
    std::unique_lock lock(this->_mutex);

    return this->_outpuPendingtWindow;
}

const Rectangle &transcoder::Compositor::Layer::getInputWindow() const {
    std::unique_lock lock(this->_mutex);

    return this->_inputPendingWindow;
}

std::recursive_mutex &transcoder::Compositor::Layer::getMutex() {
    return this->_mutex;
}

void transcoder::Compositor::Layer::_setWindows(int transitionMs) {
    std::unique_lock lock(this->_mutex);

    const auto &in  = this->_inputPendingWindow;
    const auto &out = this->_outpuPendingtWindow;

    GstClockTime startTime;

    {
        const utpl::pipeline::GstElementPtr &clockSource = 
            this->_cropElement ? **(this->_cropElement) : this->_compositorPad->getParent();

        startTime = gst_element_get_current_running_time(clockSource.get());
    }

    {
        auto &crop = this->_cropElement;
        if (crop) {
            gint left   = 0;
            gint top    = 0;
            gint right  = 0;
            gint bottom = 0;

            left = in.x() > 0 ? in.x() : 0;
            top  = in.y() > 0 ? in.y() : 0;

            if (in.width() != this->_layerSize.width()) {
                right = this->_layerSize.width() - in.width() - in.x();
            }

            if (in.height() != this->_layerSize.height()) {
                bottom = this->_layerSize.height() - in.height() - in.y();
            }
            
            DBG(("Setting crop coordinates: left {}, top {}, right {}, bottom {}",
                left, top, right, bottom
            ));

            if (transitionMs > 0) {
                _scheduleTransition(GST_OBJECT((*crop)->get()), "left",   startTime, transitionMs, crop->getProperty<gint>("left"),   left);
                _scheduleTransition(GST_OBJECT((*crop)->get()), "top",    startTime, transitionMs, crop->getProperty<gint>("top"),    top);
                _scheduleTransition(GST_OBJECT((*crop)->get()), "right",  startTime, transitionMs, crop->getProperty<gint>("right"),  right);
                _scheduleTransition(GST_OBJECT((*crop)->get()), "bottom", startTime, transitionMs, crop->getProperty<gint>("bottom"), bottom);

            } else {
                crop->setProperty<gint>("left",   left);
                crop->setProperty<gint>("top",    top);
                crop->setProperty<gint>("right",  right);
                crop->setProperty<gint>("bottom", bottom);
            }
        }
    }

    {
        auto &pad = this->_compositorPad;

        DBG(("Setting input layer size to: {}, {}, {}, {}",
            out.x(), out.y(), out.width(), out.height()
        ));

        if (transitionMs > 0) {
            _scheduleTransition(GST_OBJECT((*pad)->get()), "xpos",   startTime, transitionMs, pad->getProperty<gint>("xpos"),   out.x());
            _scheduleTransition(GST_OBJECT((*pad)->get()), "ypos",   startTime, transitionMs, pad->getProperty<gint>("ypos"),   out.y());
            _scheduleTransition(GST_OBJECT((*pad)->get()), "width",  startTime, transitionMs, pad->getProperty<gint>("width"),  out.width());
            _scheduleTransition(GST_OBJECT((*pad)->get()), "height", startTime, transitionMs, pad->getProperty<gint>("height"), out.height());

        } else {
            pad->setProperty<gint>("xpos",   out.x());                    
            pad->setProperty<gint>("ypos",   out.y());
            pad->setProperty<gint>("width",  out.width());
            pad->setProperty<gint>("height", out.height());
        }
    }

    this->_inputWindow  = this->_inputPendingWindow;
    this->_outputWindow = this->_outpuPendingtWindow;
}

void transcoder::Compositor::Layer::setWindows(const Rectangle &inputWindow, const Rectangle &outputWindow, int transitionMs) {
    bool changed = false;

    std::unique_lock lock(this->_mutex);

    if (
        (this->_inputPendingWindow  != inputWindow) ||
        (this->_outpuPendingtWindow != outputWindow)
    ) {
        changed = true;
    }

    if (changed) {
        pipeline::PadPtr pad;

        this->_inputPendingWindow  = inputWindow;
        this->_outpuPendingtWindow = outputWindow;

        DBG(("Applying layer window src: {}, {}, {}, {}; dst: {}, {}, {}, {}; on layer size: {}, {}, {}, {}",
            inputWindow.x(), inputWindow.y(), inputWindow.width(), inputWindow.height(),
            outputWindow.x(), outputWindow.y(), outputWindow.width(), outputWindow.height(),
            _layerSize.x(), _layerSize.y(), _layerSize.width(), _layerSize.height()
        ));

        if (this->_cropElement) {
            pad = this->_cropElement->getPad("sink");

        } else {
            pad = this->_compositorPad;
        }

        if (pad) {
            _setWindows(transitionMs);
        }
    }
}

void transcoder::Compositor::Layer::setSize(const Rectangle &rect) {
    std::unique_lock lock(this->_mutex);

    DBG(("Setting layer size to: {}, {}, {}, {}", rect.x(), rect.y(), rect.width(), rect.height()));

    if (this->_layerSize != rect) {
        Rectangle newInputWindow  = this->_inputPendingWindow;
        Rectangle newOutputWindow = this->_outpuPendingtWindow;

        double scaleXFactor = (double) rect.width() / this->_layerSize.width();
        double scaleYFactor = (double) rect.height() / this->_layerSize.height();

        if (newInputWindow == this->_layerSize) {
            newInputWindow = rect;

        } else {
            newInputWindow.width (newInputWindow.width()  * scaleXFactor);
            newInputWindow.height(newInputWindow.height() * scaleYFactor);            
        }

        if (newOutputWindow == this->_layerSize) {
            newOutputWindow = rect;

        } else {
            newOutputWindow.width (newOutputWindow.width()  * scaleXFactor);
            newOutputWindow.height(newOutputWindow.height() * scaleYFactor);            
        }

        this->_layerSize = rect;

        this->setWindows(newInputWindow, newOutputWindow);
    }
}

pipeline::PadPtr transcoder::Compositor::Layer::getSinkPad() {
    return this->_sinkPad;
}

pipeline::PadPtr transcoder::Compositor::Layer::getCompositorPad() {
    return this->_compositorPad;
}

GstClockTime transcoder::Compositor::Layer::getRunningTime() const {
    // A pad position is expressed in its current segment and may reset whenever
    // a playlist advances to another file.  Overlay appsrc timestamps must use
    // the continuously increasing pipeline running time expected by compositor.
    const auto clockSource = this->_compositorPad->getParent();
    if (clockSource) {
        return gst_element_get_current_running_time(clockSource.get());
    }

    return GST_CLOCK_TIME_NONE;
}

