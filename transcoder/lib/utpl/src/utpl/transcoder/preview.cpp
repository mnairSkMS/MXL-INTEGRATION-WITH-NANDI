using namespace utpl;

// Frame width of every preview JPEG; height follows the picture's aspect ratio.
#define PREVIEW_WIDTH     640
#define PREVIEW_STILL_FPS 2
#define PREVIEW_LIVE_FPS  10

transcoder::PreviewTap::PreviewTap(InputStream *stream, bool encoded) {
    this->_stream  = stream;
    this->_encoded = encoded;

    // The leaky queue is the only element here that can hold a buffer; on overload it
    // drops. In STILL mode it only ever holds keyframes. It is short for decoded video:
    // a few raw 1080 frames are already tens of megabytes.
    this->_bin = pipeline::Bin::parse(
        "preview-" + std::to_string(utils::AutoGeneratedId().getInt()),
        "valve name=valve drop=true"
        " ! identity name=keyframes"
        " ! queue leaky=downstream max-size-buffers=" + std::string(encoded ? "120" : "3") +
        " max-size-bytes=0 max-size-time=0 silent=true"
        " ! appsink name=feed sync=false async=false max-buffers=" + std::string(encoded ? "4" : "1") +
        " drop=true emit-signals=true"
    );

    GstBin *bin = GST_BIN((*this->_bin)->get());

    this->_valve     = gst_bin_get_by_name(bin, "valve");
    this->_keyframes = gst_bin_get_by_name(bin, "keyframes");

    {
        GstElement *feed = gst_bin_get_by_name(bin, "feed");

        g_signal_connect(feed, "new-sample", G_CALLBACK(onFeed), this);
        gst_object_unref(feed);
    }

    PreviewHub::instance().registerTap(stream, this);
}

transcoder::PreviewTap::~PreviewTap() {
    PreviewHub::instance().unregisterTap(this->_stream);

    // Not under _guard: the renderer's streaming thread may be waiting for it inside
    // onSample(), and stopping the renderer waits for that thread.
    this->_stopRenderer(true);

    for (auto *element : {this->_valve, this->_keyframes}) {
        if (element) {
            gst_object_unref(element);
        }
    }
}

pipeline::BinPtr transcoder::PreviewTap::getBin() {
    return this->_bin;
}

GstElement *transcoder::PreviewTap::_startRenderer(GstCaps *caps) {
    std::string desc = "appsrc name=src is-live=true format=time max-buffers=2 leaky-type=downstream";

    if (this->_encoded) {
        desc += " ! decodebin name=decoder";
    }

    // The deinterlacer comes first because it also sets frame durations, which buffers
    // arriving through appsrc lack and videorate needs. Linear, one field per frame, is the
    // cheapest method. Scaling happens before colour conversion, on the full-size picture
    // in its source format, so conversion only touches 640-wide frames.
    //
    // Decoded streams are already thinned in onFeed(); a second limiter would drop frames
    // whose spacing jitters just under the interval, so only encoded streams get one.
    desc += " ! deinterlace mode=auto method=linear fields=top";

    if (this->_encoded) {
        desc +=
            " ! videorate name=rate drop-only=true max-rate=" +
            std::to_string(this->_mode == PreviewMode::LIVE ? PREVIEW_LIVE_FPS : PREVIEW_STILL_FPS);
    }

    desc +=
        " ! videoscale"
        " ! video/x-raw,width=" + std::to_string(PREVIEW_WIDTH) + ",pixel-aspect-ratio=1/1"
        " ! videoconvert ! jpegenc quality=75"
        " ! appsink name=sink sync=false max-buffers=1 drop=true emit-signals=true";

    GError     *error    = nullptr;
    GstElement *renderer = gst_parse_launch(desc.c_str(), &error);

    if (! renderer) {
        WARN(("Unable to build the preview renderer: {}", error ? error->message : "?"));
        g_clear_error(&error);

        return nullptr;
    }

    // Nothing reads this bus; drop its messages instead of letting them pile up, and log
    // errors so a stream the preview cannot decode is visible without touching on-air.
    {
        GstBus *bus = gst_element_get_bus(renderer);

        gst_bus_set_sync_handler(bus, +[](GstBus *, GstMessage *message, gpointer) -> GstBusSyncReply {
            if (GST_MESSAGE_TYPE(message) == GST_MESSAGE_ERROR) {
                GError *err = nullptr;
                gst_message_parse_error(message, &err, nullptr);
                WARN(("Input preview renderer error: {}", err ? err->message : "?"));
                g_clear_error(&err);
            }

            return GST_BUS_DROP;
        }, nullptr, nullptr);

        gst_object_unref(bus);
    }

    this->_source = gst_bin_get_by_name(GST_BIN(renderer), "src");
    this->_rate   = gst_bin_get_by_name(GST_BIN(renderer), "rate");

    gst_app_src_set_caps(GST_APP_SRC(this->_source), caps);

    if (this->_encoded) {
        GstElement *decoder = gst_bin_get_by_name(GST_BIN(renderer), "decoder");

        // Bounded so a live preview cannot take every core from the on-air encode.
        g_signal_connect(decoder, "deep-element-added", G_CALLBACK(+[](GstBin *, GstBin *, GstElement *element, gpointer) {
            if (g_object_class_find_property(G_OBJECT_GET_CLASS(element), "max-threads")) {
                g_object_set(element, "max-threads", 2, nullptr);
            }
        }), nullptr);

        gst_object_unref(decoder);
    }

    {
        GstElement *sink = gst_bin_get_by_name(GST_BIN(renderer), "sink");

        g_signal_connect(sink, "new-sample", G_CALLBACK(onSample), this);
        gst_object_unref(sink);
    }

    gst_element_set_state(renderer, GST_STATE_PLAYING);

    this->_renderer = renderer;

    return renderer;
}

void transcoder::PreviewTap::_stopRenderer(bool synchronous) {
    GstElement *renderer;
    GstElement *source;
    GstElement *rate;

    {
        std::unique_lock lock(this->_guard, std::defer_lock);

        // apply() already holds the lock when it calls this; the destructor does not.
        if (synchronous) {
            lock.lock();
        }

        renderer = this->_renderer;
        source   = this->_source;
        rate     = this->_rate;

        this->_renderer = this->_source = this->_rate = nullptr;
    }

    if (! renderer) {
        return;
    }

    auto stop = [renderer, source, rate]() {
        gst_element_set_state(renderer, GST_STATE_NULL);
        gst_object_unref(source);
        if (rate) {
            gst_object_unref(rate);
        }
        gst_object_unref(renderer);
    };

    if (synchronous) {
        // The tap is going away: no callback may reach it once this returns.
        GstElement *sink = gst_bin_get_by_name(GST_BIN(renderer), "sink");

        g_signal_handlers_disconnect_by_data(sink, this);
        gst_object_unref(sink);

        stop();

    } else {
        // Can be called from the renderer's own streaming thread (onSample -> apply),
        // which cannot wait for itself to stop. The tap outlives this, so a callback
        // still in flight is harmless.
        std::thread(stop).detach();
    }
}

void transcoder::PreviewTap::apply(PreviewMode mode) {
    std::unique_lock lock(this->_guard);

    if (mode == this->_mode) {
        return;
    }

    if (mode != PreviewMode::OFF) {
        // STILL lets only keyframes through to the decoder; LIVE needs every frame.
        guint flags = (mode == PreviewMode::STILL && this->_encoded) ? GST_BUFFER_FLAG_DELTA_UNIT : 0;

        g_object_set(this->_keyframes, "drop-buffer-flags", flags, nullptr);

        if (this->_rate) {
            g_object_set(this->_rate, "max-rate", mode == PreviewMode::LIVE ? PREVIEW_LIVE_FPS : PREVIEW_STILL_FPS, nullptr);
        }
    }

    g_object_set(this->_valve, "drop", mode == PreviewMode::OFF, nullptr);

    if (mode == PreviewMode::OFF) {
        this->_stopRenderer(false);
    }

    LOG(("Input preview {} -> {}", (void *) this, mode == PreviewMode::OFF ? "off" : mode == PreviewMode::STILL ? "still" : "live"));

    this->_mode = mode;
}

GstFlowReturn transcoder::PreviewTap::onFeed(GstElement *sink, gpointer data) {
    auto *self   = static_cast<PreviewTap *>(data);
    auto *sample = gst_app_sink_pull_sample(GST_APP_SINK(sink));

    if (! sample) {
        return GST_FLOW_OK;
    }

    {
        std::unique_lock lock(self->_guard);

        if (self->_mode != PreviewMode::OFF) {
            GstCaps *caps = gst_sample_get_caps(sample);

            if (! self->_renderer && caps) {
                self->_startRenderer(caps);

            } else if (self->_renderer && caps) {
                // The stream can change format, for example on a live codec switch.
                GstCaps *current = gst_app_src_get_caps(GST_APP_SRC(self->_source));

                if (! current || ! gst_caps_is_equal(current, caps)) {
                    gst_app_src_set_caps(GST_APP_SRC(self->_source), caps);
                }

                if (current) {
                    gst_caps_unref(current);
                }
            }

            GstBuffer *buffer = gst_sample_get_buffer(sample);

            // Decoded frames do not depend on each other, so surplus ones are dropped here,
            // before the renderer deinterlaces or scales them. Encoded frames all have to
            // reach the decoder (in STILL mode the keyframe filter already thinned them).
            if (! self->_encoded) {
                auto now      = std::chrono::steady_clock::now();
                auto interval = std::chrono::milliseconds(1000 / (self->_mode == PreviewMode::LIVE ? PREVIEW_LIVE_FPS : PREVIEW_STILL_FPS));

                if (now - self->_lastPush < interval) {
                    buffer = nullptr;

                } else {
                    self->_lastPush = now;
                }
            }

            if (self->_source && buffer) {
                gst_app_src_push_buffer(GST_APP_SRC(self->_source), gst_buffer_ref(buffer));
            }
        }
    }

    gst_sample_unref(sample);

    return GST_FLOW_OK;
}

GstFlowReturn transcoder::PreviewTap::onSample(GstElement *sink, gpointer data) {
    auto *self   = static_cast<PreviewTap *>(data);
    auto *sample = gst_app_sink_pull_sample(GST_APP_SINK(sink));

    if (! sample) {
        return GST_FLOW_OK;
    }

    std::string path;
    auto mode = PreviewHub::instance().currentMode(self->_stream, path);

    if (mode == PreviewMode::OFF || path.empty()) {
        self->apply(PreviewMode::OFF);

    } else {
        self->apply(mode);

        GstBuffer *buffer = gst_sample_get_buffer(sample);
        GstMapInfo map;

        if (buffer && gst_buffer_map(buffer, &map, GST_MAP_READ)) {
            // Write beside the target and rename, so a reader never sees half a JPEG.
            std::string partial = path + ".partial";

            {
                std::ofstream out(partial, std::ios::binary | std::ios::trunc);
                out.write(reinterpret_cast<const char *>(map.data), map.size);
            }

            std::error_code error;
            std::filesystem::rename(partial, path, error);

            if (error) {
                WARN(("Unable to publish preview frame {}: {}", path, error.message()));
            }

            gst_buffer_unmap(buffer, &map);
        }
    }

    gst_sample_unref(sample);

    return GST_FLOW_OK;
}

transcoder::PreviewHub &transcoder::PreviewHub::instance() {
    static PreviewHub hub;

    return hub;
}

transcoder::PreviewHub::PreviewHub() {
    const char *enabled   = std::getenv("UTPL_PREVIEW");
    const char *directory = std::getenv("UTPL_PREVIEW_DIR");

    this->_enabled = ! (enabled && (std::string(enabled) == "off" || std::string(enabled) == "0"));

    if (directory && *directory) {
        this->_directory = directory;
    }
}

bool transcoder::PreviewHub::isEnabled() const {
    return this->_enabled;
}

void transcoder::PreviewHub::setDirectory(const std::string &directory) {
    std::unique_lock lock(this->_guard);

    this->_directory = directory;
}

std::string transcoder::PreviewHub::framePath(const std::string &inputId) {
    std::unique_lock lock(this->_guard);

    return this->_directory + "/" + inputId + ".jpg";
}

int transcoder::PreviewHub::demand(
    const std::string &inputId,
    PreviewMode mode,
    std::chrono::milliseconds ttl,
    const std::vector<InputStream *> &videoStreams
) {
    std::vector<PreviewTap *> taps;
    PreviewMode               effective;

    {
        std::unique_lock lock(this->_guard);

        {
            std::error_code error;
            std::filesystem::create_directories(this->_directory, error);
        }

        auto  until  = std::chrono::steady_clock::now() + ttl;
        auto &demand = this->_demands[inputId];

        if (mode == PreviewMode::LIVE) {
            demand.live = until;

        } else if (mode == PreviewMode::STILL) {
            demand.still = until;

        } else {
            demand = Demand{};
        }

        effective = this->_modeOf(inputId);

        DBG(("Preview demand for input {}: {} video streams, {} taps registered", inputId, videoStreams.size(), this->_taps.size()));

        for (auto *stream : videoStreams) {
            this->_bindings[stream] = inputId;

            auto it = this->_taps.find(stream);

            if (it != this->_taps.end()) {
                taps.push_back(it->second);
            }
        }
    }

    // Outside the hub lock: apply() takes the tap's own lock, which onSample() holds while
    // it calls back into the hub.
    for (auto *tap : taps) {
        tap->apply(effective);
    }

    return (int) taps.size();
}

void transcoder::PreviewHub::registerTap(InputStream *stream, PreviewTap *tap) {
    std::unique_lock lock(this->_guard);

    this->_taps[stream] = tap;
}

void transcoder::PreviewHub::unregisterTap(InputStream *stream) {
    std::unique_lock lock(this->_guard);

    this->_taps.erase(stream);
    this->_bindings.erase(stream);
}

transcoder::PreviewMode transcoder::PreviewHub::currentMode(InputStream *stream, std::string &path) {
    std::unique_lock lock(this->_guard);

    auto it = this->_bindings.find(stream);

    if (it == this->_bindings.end()) {
        return PreviewMode::OFF;
    }

    path = this->_directory + "/" + it->second + ".jpg";

    return this->_modeOf(it->second);
}

transcoder::PreviewMode transcoder::PreviewHub::_modeOf(const std::string &inputId) {
    auto it = this->_demands.find(inputId);

    if (it == this->_demands.end()) {
        return PreviewMode::OFF;
    }

    auto now = std::chrono::steady_clock::now();

    if (it->second.live > now) {
        return PreviewMode::LIVE;
    }

    if (it->second.still > now) {
        return PreviewMode::STILL;
    }

    return PreviewMode::OFF;
}
