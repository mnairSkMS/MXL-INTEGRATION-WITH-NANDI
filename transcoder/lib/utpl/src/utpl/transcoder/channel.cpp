transcoder::Channel::AudioBlankHold::AudioBlankHold(Channel *channel) {
    if (! channel) {
        return;
    }

    this->_channel = channel;
    this->_token   = channel->acquireAudioBlank(&this->_generation);
}

transcoder::Channel::AudioBlankHold::~AudioBlankHold() {
    this->release();
}

transcoder::Channel::AudioBlankHold::AudioBlankHold(AudioBlankHold &&other) noexcept {
    this->_channel    = other._channel;
    this->_token      = other._token;
    this->_generation = other._generation;

    // The moved-from holder must not release what it no longer owns.
    other._channel = nullptr;
    other._token   = 0;
}

transcoder::Channel::AudioBlankHold &transcoder::Channel::AudioBlankHold::operator=(AudioBlankHold &&other) noexcept {
    if (this == &other) {
        return *this;
    }

    this->release();

    this->_channel    = other._channel;
    this->_token      = other._token;
    this->_generation = other._generation;

    other._channel = nullptr;
    other._token   = 0;

    return *this;
}

void transcoder::Channel::AudioBlankHold::release() {
    if (! this->_channel) {
        return;
    }

    // Cleared before the call, so a re-entrant path cannot release the same token twice.
    auto *channel   = this->_channel;
    auto token      = this->_token;
    auto generation = this->_generation;

    this->_channel = nullptr;
    this->_token   = 0;

    channel->releaseAudioBlank(token, generation);
}

