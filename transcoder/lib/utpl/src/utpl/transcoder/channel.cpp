        pipeline::TimedCallbackId addTimedCallback(
            Timestamp callTime, Timestamp interval, TimedCallbackSource src, std::function<bool(pipeline::TimedCallbackId, GstClockTime time)> callback
        ) {
            pipeline::TimedCallbackId ret = nullptr;

            {
                GstClock *srcClock = nullptr;

                {
                    GstElement *el = nullptr;

                    switch (src) {
                        case TimedCallbackSource::COMPOSITOR:
                            {
                                if (this->_videoConnector) {
                                    el = *this->_videoConnector->getCompositor()->getSrcPad()->getParent();
                                }
                            }
                            break;

                        case TimedCallbackSource::PROCESSOR:
                            {
                                if (! el) {
                                    if (this->_videoConnector) {
                                        el = *this->_videoConnector->getCompositor()->getSrcPad()->getParent();
                                    }
                                }

                                if (! el) {
                                    for (auto &videoProcessor : this->_videoProcessors) {
                                        auto compositor = videoProcessor->getCompositor();
                                        if (compositor) {
                                            el = *compositor->getSrcPad()->getParent();
                                            break;
                                        }
                                    }
                                }

                                if (! el) {
                                    if (this->_audioConnector) {
                                        auto muter = this->_audioConnector->getMuter();
                                        if (muter) {
                                            el = (*muter)->get();
                                        }
                                    }
                                }

                                if (! el) {
                                    if (this->_dolbyConnector) {
                                        auto muter = this->_dolbyConnector->getMuter();
                                        if (muter) {
                                            el = (*muter)->get();
                                        }
                                    }
                                }

                                if (! el) {
                                    for (auto &audioProcessor : this->_audioProcessors) {
                                        auto muter = audioProcessor->getMuter();

                                        if (muter) {
                                            el = (*muter)->get();
                                            break;
                                        }
                                    }
                                }

                                if (! el) {
                                    for (auto &captionProcessor : this->_captionProcessors) {
                                        auto muter = captionProcessor->getMuter();

                                        if (muter) {
                                            el = (*muter)->get();
                                            break;
                                        }
                                    }
                                }
                            }
                            break;

                        case TimedCallbackSource::OUTPUT:
                            {
                                if (! this->_outputs.empty()) {
                                    for (auto &o : this->_outputs) {
                                        for (auto &s : o.first->getStreams()) {
                                            auto &params = s->getStreamParameters();
                                            if (params.hasVideoParameters()) {
                                                auto pad = s->getPad();

                                                if (pad->isLinked()) {
                                                    el = *pad->getParent();
                                                    break;
                                                }
                                            }
                                        }

                                        if (! el) {
                                            for (auto &s : o.first->getStreams()) {
                                                auto &params = s->getStreamParameters();
                                                if (params.hasAudioParameters()) {
                                                    auto pad = s->getPad();

                                                    if (pad->isLinked()) {
                                                        el = *pad->getParent();
                                                        break;
                                                    }
                                                }
                                            }   
                                        }

                                        if (el) {
                                            break;
                                        }
                                    }
                                }
                            }
                            break;
                    }

                    if (el) {
                        srcClock = gst_element_get_clock(el);
                    }
                }

                if (srcClock) {
                    Timestamp offset = callTime - Time::getUTCTimestamp();

                    GstClockTime targetTime = gst_clock_get_time(srcClock) + offset * GST_MSECOND;

                    {
                        GstClockID id;

                        if (interval) {
                            id = gst_clock_new_periodic_id(srcClock, targetTime, interval * GST_MSECOND);

                        } else {
                            id = gst_clock_new_single_shot_id(srcClock, targetTime);
                        }

                        {
                            std::lock_guard guard(this->_timedCallbacksGuard);

                            this->_timedCallbacks[id] = callback;
                        }

                        gst_clock_id_wait_async(id, (GstClockCallback) _clockCallback, this, nullptr);

                        ret = id;
                    }

                    gst_object_unref(srcClock);
                }    
            }

            return ret;
        }
        
        void cancelTimedCallback(pipeline::TimedCallbackId callbackId) {
            std::lock_guard guard(this->_timedCallbacksGuard);

            auto it = this->_timedCallbacks.find(callbackId);
            if (it == this->_timedCallbacks.end()) {
                WARN(("Channel know nothing about timer ID {}", (void *) callbackId));

            } else {
                auto id = it->first;

                gst_clock_id_unschedule(id);
                gst_clock_id_unref(id);

                this->_timedCallbacks.erase(it);

                DBG(("Timed callback id id {} was successfully removed, {} remain", callbackId, this->_timedCallbacks.size()));
            }
        }

        void sendScteToOutputs(const Scte35Data &data) {
            // Local consumers first: blanking and ad insertion both act on conditioned events,
            // so a POIS DELETE removes the event for them too.
            for (auto &callback : this->_scteCallbacks) {
                callback(data);
            }

            // With ad insertion set to suppress, the break window carries no markers downstream:
            // the content has already been replaced here, and a downstream splicer must not
            // replace it again. Default is PASSTHROUGH, which leaves this loop as it was.
            if (this->_scteSuppression && this->_scteSuppression()) {
                DBG(("Suppressing SCTE section while a locally inserted break is on air"));

                return;
            }

            for (auto &output : this->_outputs) {
                const auto &scteParams = output.second.getScteParameters();

                if (scteParams.getMode() == ScteOutputMode::PASSTHROUGH) {
                    output.first->putScteData(data);
                }
            }
        }

        void injectScte35Event(const Scte35Data &data) {
            const auto &poisParams = this->_scteParametres.getPoisParameters();

            LOG(("Injecting SCTE-35 {} (POIS conditioning {}): {}",
                data.isSpliceInsert() ? "splice_insert" : (data.isTimeSignal() ? "time_signal" : "section"),
                poisParams.isEnabled() ? "enabled" : "disabled",
                toBase64(data)
            ));

            if (! poisParams.isEnabled()) {
                // No POIS
                this->sendScteToOutputs(data);

            } else {
                do {
                    auto *section = (GstMpegtsSection *) data.getSection();
                    auto *sit     = gst_mpegts_section_get_scte_sit(section);

                    if (! sit) {
                        WARN(("Unable to parse SCTE35 section"));
                        
                        break;
                    }

                    if (
                        sit->splice_command_type != GST_MTS_SCTE_SPLICE_COMMAND_INSERT &&
                        sit->splice_command_type != GST_MTS_SCTE_SPLICE_COMMAND_TIME
                    ) {
                        this->sendScteToOutputs(data);

                        break;
                    }

                    {
                        esam::SignalParameters signalParams;

                        signalParams.acquisitionTime = Time::getUTCTimestamp();

                        {
                            auto pts = sit->pts_adjustment;

                            if (sit->splice_command_type == GST_MTS_SCTE_SPLICE_COMMAND_INSERT) {
                                if (sit->splices->len > 0) {
                                    GstMpegtsSCTESpliceEvent *event = (GstMpegtsSCTESpliceEvent *)g_ptr_array_index(sit->splices, 0);

                                    pts += event->program_splice_time;
                                }
                            }

                            if (sit->splice_command_type == GST_MTS_SCTE_SPLICE_COMMAND_TIME) {
                                pts += sit->splice_time;
                            }

                            signalParams.pts = pts;
                        }

                        if (
                            GST_CLOCK_TIME_IS_VALID(data.getSpliceTime()) && 
                            GST_CLOCK_TIME_IS_VALID(data.getRunningTime())
                        ) {
                            signalParams.signalTimestamp += GST_TIME_AS_MSECONDS(data.getSpliceTime() - data.getRunningTime());
                        }

                        {
                            gsize dataSize;

                            auto *data = gst_mpegts_section_packetize(section, &dataSize);
                            if (data == nullptr) {
                                ERR(("Failed to packetize section"));

                                break;
                            }

                            signalParams.sectionData.assign(data, data + dataSize);
                        }
                        
                        this->_esamClient.signalEventAsync(signalParams, [&](utpl::esam::EventResponse &response, bool success) {
                            if (! success) {
                                ERR(("Failed to signal event to POIS"));
                                return;
                            }

                            switch(response.mode) {
                                case utpl::esam::Operation::NOOP:
                                    this->sendScteToOutputs(data);
                                    break;

                                case utpl::esam::Operation::DELETE:
                                    // ignore the event
                                    break;

                                case utpl::esam::Operation::REPLACE:
                                    {
                                        Scte35Data newData;

                                        if (response.sectionData.empty()) {
                                            ERR(("No section data in response"));
                                            break;
                                        }
                                        
                                        {
                                            auto *responseSection = gst_mpegts_section_new(
                                                section->pid, 
                                                (guint8 *) g_memdup2(
                                                    response.sectionData.data(), response.sectionData.size()
                                                ), 
                                                response.sectionData.size()
                                            );
                                            
                                            if (responseSection) {
                                                newData.setSection(responseSection);
                                                newData.setTimingMap(
                                                    gst_structure_copy(data.getTimingMap())
                                                );

                                                gst_mpegts_section_unref(responseSection);
                                            }
                                        }

                                        this->sendScteToOutputs(newData);
                                    }
                                    break;

                                default:
                                    WARN(("Not supported POIS conditioning operation mode: {}", (int) response.mode));
                                    break;
                            }
                        });
                    }
                } while (0);
            }
        }


        static gboolean _clockCallback(GstClock *clock, GstClockTime time, GstClockID id, Pimpl *self) {
            std::lock_guard guard(self->_timedCallbacksGuard);

            auto it = self->_timedCallbacks.find(id);
            if (it != self->_timedCallbacks.end()) {
                if (! it->second(id, time)) {
                    gst_clock_id_unref(it->first);

                    self->_timedCallbacks.erase(it);

                    DBG(("Timed callback of id {} is no longer required and has been removed from the running callbacks list, {} remain", id, self->_timedCallbacks.size()));
                }
            }

            return false;
        }

