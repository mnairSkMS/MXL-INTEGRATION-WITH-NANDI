Rectangle calcWindow(const Rectangle &window, const Rectangle &originalWindow, bool scale) {
    Rectangle ret = window;

    if (ret.x() < 0) {
        ret.x(originalWindow.x());
    }

    if (ret.y() < 0) {
        ret.y(originalWindow.y());
    }

    if (ret.width() < 0 && ret.height() < 0) {
        ret.width(originalWindow.width() - ret.x());
        ret.height(originalWindow.height() - ret.y());

    } else if (ret.width() < 0 && ret.height()) {
        if (scale) {
            int height = ret.height() - ret.y();
            if (height != originalWindow.height()) {
                float ratio = (float) height / originalWindow.height();

                ret.width(originalWindow.width() * ratio);

            } else {
                ret.width(originalWindow.width());
            }

        } else {
            ret.width(originalWindow.width());
        }

    } else if (ret.height() < 0 && ret.width()) {
        if (scale) {
            int width = ret.width() - ret.x();

            if (width != originalWindow.width()) {
                float ratio = (float) width / originalWindow.width();

                ret.height(originalWindow.height() * ratio);

            } else {
                ret.height(originalWindow.height());
            }
            
        } else {
            ret.height(originalWindow.height());
        }
    }

    TRACE(("Recalculated window '{}, {}, {}, {}' into '{}, {}, {}, {}'",
        window.x(), window.y(), window.width(), window.height(),
        ret.x(), ret.y(), ret.width(), ret.height()
    ));

    return ret;
}

void transcoder::Channel::squeeze(const NormRect &srcNorm, const NormRect &dstNorm, int transitionMs) {
    auto compositor = this->getVideoCompositor();
    if (! compositor) {
        WARN(("Squeeze operation cannot be performed - no available video compositor found"));

    } else {
        const auto &compositorFrame = compositor->getWindowSize();

        auto layer = compositor->getVideoLayer();
        if (! layer) {
            WARN(("Squeeze operation cannot be performed - no available video layer found"));

        } else {
            const Rectangle srcWindow = srcNorm.resolve(compositorFrame);
            const Rectangle dstWindow = dstNorm.resolve(compositorFrame);

            Rectangle src;
            Rectangle dst;

            DBG(("Applying squeeze windows, src {}, {}, {}, {}, dst {}, {}, {}, {}, compositor size: {}, {}, {}, {}",
                srcWindow.x(), srcWindow.y(), srcWindow.width(), srcWindow.height(),
                dstWindow.x(), dstWindow.y(), dstWindow.width(), dstWindow.height(),
                compositorFrame.x(), compositorFrame.y(), compositorFrame.width(), compositorFrame.height()
            ));

            if (srcWindow != compositorFrame) {
                // Crop
                src = calcWindow(srcWindow, compositorFrame, false);
                dst = calcWindow(dstWindow, src,             true);

                DBG(("Squeeze is equivalent to crop; recalculated window src: {}, {}, {}, {}; dst: {}, {}, {}, {}",
                    src.x(), src.y(), src.width(), src.height(),
                    dst.x(), dst.y(), dst.width(), dst.height()
                ));

            } else {
                // Resize
                src = srcWindow;
                dst = calcWindow(dstWindow, compositorFrame, true);

                DBG(("Squeeze is equivalent to resize; recalculated window src: {}, {}, {}, {}; dst: {}, {}, {}, {}",
                    src.x(), src.y(), src.width(), src.height(),
                    dst.x(), dst.y(), dst.width(), dst.height()
                ));
            }

            layer->setWindows(src, dst, transitionMs);
        }
    }
}

