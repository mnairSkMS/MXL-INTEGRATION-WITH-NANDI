#include <cstdio>
#include <set>

#include <gst/app/gstappsink.h>
#include <gst/app/gstappsrc.h>

#include "utpl/common/debug.h"
#include "utpl/common/utils.h"

#include "utpl/transcoder/mxltap.h"

using namespace utpl;

// After a failure the side pipeline is not restarted for this long, so a persistent fault (for
// example a full tmpfs) costs one attempt every few seconds and not one per frame.
#define MXL_TAP_RETRY_SECONDS 5

namespace {
    // One writer per flow: a second tap on the same flow would fight the first over its memory.
    std::mutex       g_ownersGuard;
    std::set<std::string> g_owners;
}

std::unique_ptr<transcoder::MxlTap> transcoder::MxlTap::create(const MxlTapParameters &parameters, Kind kind) {
    const auto &flowId = (kind == Kind::VIDEO) ? parameters.getVideoFlowId() : parameters.getAudioFlowId();

    if (! parameters.isEnabled() || flowId.empty()) {
        return nullptr;
    }

    if (GstElementFactory *factory = gst_element_factory_find("mxlsink")) {
        gst_object_unref(factory);

    } else {
        WARN(("MXL tap disabled: the GStreamer element 'mxlsink' is not installed"));

        return nullptr;
    }

    const std::string owner = parameters.getDomain() + "|" + flowId;

    {
        std::lock_guard lock(g_ownersGuard);

        if (! g_owners.insert(owner).second) {
            WARN(("MXL tap disabled for flow {}: another stream already writes it", flowId));

            return nullptr;
        }
    }

    return std::unique_ptr<MxlTap>(new MxlTap(parameters, kind, owner));
}

transcoder::MxlTap::MxlTap(const MxlTapParameters &parameters, Kind kind, const std::string &owner) : _parameters(parameters), _kind(kind), _owner(owner) {
    this->_flowId  = (kind == Kind::VIDEO) ? parameters.getVideoFlowId() : parameters.getAudioFlowId();
    this->_retryAt = std::chrono::steady_clock::now();

    const bool video = (kind == Kind::VIDEO);

    // The queue is the only element here that can hold a buffer; when it is full it drops. It is
    // short for video because a few raw 1080 frames are already tens of megabytes.
    this->_bin = pipeline::Bin::parse(
        std::string("mxltap-") + (video ? "video-" : "audio-") + std::to_string(utils::AutoGeneratedId().getInt()),
        "queue leaky=downstream max-size-buffers=" + std::string(video ? "3" : "50") +
        " max-size-bytes=0 max-size-time=0 silent=true"
        " ! appsink name=feed sync=false async=false max-buffers=" + std::string(video ? "1" : "50") +
        " drop=true emit-signals=true"
    );

    this->_feed = gst_bin_get_by_name(GST_BIN((*this->_bin)->get()), "feed");

    g_signal_connect(this->_feed, "new-sample", G_CALLBACK(onFeed), this);
}

transcoder::MxlTap::~MxlTap() {
    if (this->_feed) {
        // No callback may reach this object once the destructor returns.
        g_signal_handlers_disconnect_by_data(this->_feed, this);
    }

    {
        std::lock_guard lock(this->_guard);
        this->_stop();
    }

    if (this->_feed) {
        gst_object_unref(this->_feed);
    }

    std::lock_guard lock(g_ownersGuard);
    g_owners.erase(this->_owner);
}

pipeline::BinPtr transcoder::MxlTap::getBin() {
    return this->_bin;
}

std::string transcoder::MxlTap::_describe() const {
    char buffer[512];

    if (this->_kind == Kind::VIDEO) {
        // The deinterlacer passes progressive pictures through. For interlaced ones it keeps one
        // field per frame, so the frame rate is unchanged: an MXL video flow is progressive.
        std::snprintf(buffer, sizeof(buffer),
            "appsrc name=src is-live=true format=time max-buffers=3 leaky-type=downstream"
            " ! deinterlace mode=auto method=linear fields=top"
            " ! videoconvert"
            " ! video/x-raw,format=v210"
            " ! mxlsink name=mxl flow-id=%s domain=%s",
            this->_flowId.c_str(), this->_parameters.getDomain().c_str());

    } else {
        const int channels = this->_parameters.getAudioChannels();

        std::snprintf(buffer, sizeof(buffer),
            "appsrc name=src is-live=true format=time max-buffers=50 leaky-type=downstream"
            " ! audioconvert ! audioresample"
            // mxlsink places every audio buffer at the sample index of its own timestamp, so
            // timestamps must be contiguous. Decoded frames carry timestamps rounded to the
            // 90 kHz clock; audiorate puts them on an exact sample grid.
            " ! audiorate"
            " ! audio/x-raw,format=F32LE,rate=48000,channels=%d,layout=interleaved,channel-mask=(bitmask)0x%x"
            " ! mxlsink name=mxl flow-id=%s domain=%s",
            channels, (1u << channels) - 1u,
            this->_flowId.c_str(), this->_parameters.getDomain().c_str());
    }

    return buffer;
}

int transcoder::MxlTap::_start(GstSample *sample) {
    GstClock *clock = gst_element_get_clock(this->_feed);

    if (! clock) {
        // The channel is not running yet. Try again with the next buffer.
        return 0;
    }

    GError     *error    = nullptr;
    GstElement *pipeline = gst_parse_launch(this->_describe().c_str(), &error);

    if (! pipeline) {
        WARN(("MXL tap {}: unable to build the side pipeline: {}", this->_flowId, error ? error->message : "?"));
        g_clear_error(&error);
        gst_object_unref(clock);

        return -1;
    }

    g_clear_error(&error);

    // Same clock and base time as the channel: a buffer's running time then names the same moment
    // in both pipelines, which is what mxlsink turns into an MXL timestamp.
    gst_pipeline_use_clock(GST_PIPELINE(pipeline), clock);
    gst_element_set_start_time(pipeline, GST_CLOCK_TIME_NONE);
    gst_element_set_base_time(pipeline, gst_element_get_base_time(this->_feed));
    gst_object_unref(clock);

    // Nothing reads this bus. Errors are logged and noted so the next buffer replaces the
    // pipeline; they are never passed on to the channel.
    {
        GstBus *bus = gst_element_get_bus(pipeline);

        gst_bus_set_sync_handler(bus, +[](GstBus *, GstMessage *message, gpointer data) -> GstBusSyncReply {
            if (GST_MESSAGE_TYPE(message) == GST_MESSAGE_ERROR) {
                auto   *self  = static_cast<MxlTap *>(data);
                GError *error = nullptr;
                gchar  *debug = nullptr;

                gst_message_parse_error(message, &error, &debug);
                WARN(("MXL tap {}: side pipeline error from {}: {} ({})", self->_flowId,
                    GST_MESSAGE_SRC_NAME(message), error ? error->message : "?", debug ? debug : "no detail"));
                g_clear_error(&error);
                g_free(debug);

                self->_errored = true;
            }

            return GST_BUS_DROP;
        }, this, nullptr);

        gst_object_unref(bus);
    }

    this->_source = gst_bin_get_by_name(GST_BIN(pipeline), "src");

    if (GstCaps *caps = gst_sample_get_caps(sample)) {
        gst_app_src_set_caps(GST_APP_SRC(this->_source), caps);
    }

    this->_pipeline = pipeline;

    if (gst_element_set_state(pipeline, GST_STATE_PLAYING) == GST_STATE_CHANGE_FAILURE) {
        WARN(("MXL tap {}: the side pipeline would not start", this->_flowId));
        this->_stop();

        return -1;
    }

    LOG(("MXL tap {} ({}) started, domain {}", this->_flowId, this->_kind == Kind::VIDEO ? "video" : "audio", this->_parameters.getDomain()));

    return 1;
}

void transcoder::MxlTap::_stop() {
    if (! this->_pipeline) {
        return;
    }

    GstElement *pipeline = this->_pipeline;
    GstElement *source   = this->_source;

    this->_pipeline = nullptr;
    this->_source   = nullptr;
    this->_shape.clear();

    // Stopping waits for the side pipeline's streaming thread, which is also what delivers its
    // errors to the handler above, so the handler is removed first.
    {
        GstBus *bus = gst_element_get_bus(pipeline);

        gst_bus_set_sync_handler(bus, nullptr, nullptr, nullptr);
        gst_object_unref(bus);
    }

    gst_element_set_state(pipeline, GST_STATE_NULL);

    if (source) {
        gst_object_unref(source);
    }

    gst_object_unref(pipeline);

    LOG(("MXL tap {} stopped after {} buffers", this->_flowId, this->_pushed));
}

GstFlowReturn transcoder::MxlTap::onFeed(GstElement *sink, gpointer data) {
    auto *self   = static_cast<MxlTap *>(data);
    auto *sample = gst_app_sink_pull_sample(GST_APP_SINK(sink));

    if (! sample) {
        return GST_FLOW_OK;
    }

    {
        std::lock_guard lock(self->_guard);

        const auto now = std::chrono::steady_clock::now();

        if (self->_errored.exchange(false)) {
            self->_stop();
            self->_restarts++;
            self->_retryAt = now + std::chrono::seconds(MXL_TAP_RETRY_SECONDS);
        }

        GstCaps   *caps   = gst_sample_get_caps(sample);
        GstBuffer *buffer = gst_sample_get_buffer(sample);

        if (now >= self->_retryAt && caps && buffer && GST_BUFFER_PTS_IS_VALID(buffer)) {
            // A new size or frame rate makes a new video flow; everything else the side pipeline
            // converts. Replace the pipeline rather than renegotiate mxlsink in place.
            std::string shape;

            if (self->_kind == Kind::VIDEO) {
                if (const GstStructure *structure = gst_caps_get_structure(caps, 0)) {
                    int width = 0, height = 0, num = 0, den = 1;

                    gst_structure_get_int(structure, "width", &width);
                    gst_structure_get_int(structure, "height", &height);
                    gst_structure_get_fraction(structure, "framerate", &num, &den);

                    shape = std::to_string(width) + "x" + std::to_string(height) + "@" + std::to_string(num) + "/" + std::to_string(den);
                }

                if (self->_pipeline && shape != self->_shape) {
                    LOG(("MXL tap {}: the picture changed from {} to {}", self->_flowId, self->_shape, shape));
                    self->_stop();
                }
            }

            if (! self->_pipeline) {
                const int started = self->_start(sample);

                if (started == 1) {
                    self->_shape = shape;

                } else if (started < 0) {
                    self->_retryAt = now + std::chrono::seconds(MXL_TAP_RETRY_SECONDS);
                }
            }

            if (self->_pipeline && self->_source) {
                GstClockTime running = gst_segment_to_running_time(gst_sample_get_segment(sample), GST_FORMAT_TIME, GST_BUFFER_PTS(buffer));

                if (GST_CLOCK_TIME_IS_VALID(running)) {
                    // A copy of the buffer header, not of the picture: the memory is shared. Only
                    // the time is changed, to the channel's running time.
                    GstBuffer *out = gst_buffer_make_writable(gst_buffer_ref(buffer));

                    GST_BUFFER_PTS(out) = running;
                    GST_BUFFER_DTS(out) = GST_CLOCK_TIME_NONE;

                    if (gst_app_src_push_buffer(GST_APP_SRC(self->_source), out) == GST_FLOW_OK) {
                        self->_pushed++;
                    }
                }
            }
        }
    }

    gst_sample_unref(sample);

    return GST_FLOW_OK;
}
